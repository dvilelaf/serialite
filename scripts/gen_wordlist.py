#!/usr/bin/env python3
"""Generate components/credentials/src/credentials_wordlist.c from the EFF large wordlist.

Words with a hyphen are dropped: the passphrase is compacted into a WPA2 key by
removing spaces, and the validators reject anything but lowercase letters.

Usage:
  scripts/gen_wordlist.py          # rewrite the generated file
  scripts/gen_wordlist.py --check  # fail if the generated file is stale
"""

from __future__ import annotations

import hashlib
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = REPO_ROOT / "components" / "credentials" / "wordlist" / "eff_large_wordlist.txt"
OUTPUT = REPO_ROOT / "components" / "credentials" / "src" / "credentials_wordlist.c"
SOURCE_SHA256 = "addd35536511597a02fa0a9ff1e5284677b8883b83e986e43f15a3db996b903e"
WORDS_PER_LINE = 8


def load_words() -> list[str]:
    raw = SOURCE.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != SOURCE_SHA256:
        raise SystemExit(f"{SOURCE} has SHA-256 {digest}, expected {SOURCE_SHA256}")

    words = []
    for line in raw.decode("ascii").splitlines():
        _, word = line.split("\t")
        if word.isascii() and word.isalpha() and word.islower():
            words.append(word)
    if len(set(words)) != len(words):
        raise SystemExit("duplicate words in source list")
    return words


def render(words: list[str]) -> str:
    lines = [
        "/*",
        " * Generated by scripts/gen_wordlist.py from wordlist/eff_large_wordlist.txt",
        f" * (SHA-256 {SOURCE_SHA256}). Do not edit by hand.",
        " *",
        " * EFF Large Wordlist, CC BY 3.0 US, https://www.eff.org/dice",
        " */",
        "",
        '#include "credentials_wordlist.h"',
        "",
        "const char *const CREDENTIALS_WORDLIST[CREDENTIALS_WORDLIST_COUNT] = {",
    ]
    for start in range(0, len(words), WORDS_PER_LINE):
        chunk = words[start : start + WORDS_PER_LINE]
        lines.append("    " + " ".join(f'"{word}",' for word in chunk))
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    words = load_words()
    rendered = render(words)
    header = (REPO_ROOT / "components" / "credentials" / "include" / "credentials_wordlist.h").read_text()
    if f"#define CREDENTIALS_WORDLIST_COUNT {len(words)}U" not in header:
        raise SystemExit(f"credentials_wordlist.h must define CREDENTIALS_WORDLIST_COUNT {len(words)}U")

    if "--check" in sys.argv[1:]:
        if OUTPUT.read_text() != rendered:
            print(f"{OUTPUT.relative_to(REPO_ROOT)} is stale; run scripts/gen_wordlist.py", file=sys.stderr)
            return 1
        return 0

    OUTPUT.write_text(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
